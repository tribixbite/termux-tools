import { existsSync, lstatSync, readFileSync } from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import {
  agxBinary, agxContext, fetchAgxManifest, importLegacyAgx, installedAgx, launchArgv, launchEnv, pruneAgx, readAgxState,
  scheduleAgx, switchAgx, updateAgx, type AgxContext,
} from "./antigravity";
import { atomicWrite, shellQuote, withDirLock } from "./managed";
import { parseManagerArgs, type ManagerArgs } from "./manager-args";

const HELP = `agx — Antigravity CLI channel manager for Termux
  agx update [--pin VERSION]       download, checksum and verify agy-next
  agx promote                     make next the stable agy
  agx rollback [--to VERSION]      switch to an archived stable version
  agx status [--json]              installed channels and Google's current release
  agx list                        installed, archived and catalogued versions
  agx prune [--keep N] [--yes]      preview deletion; --yes applies (default keep 2)
  agx setup                       install agx, agy and agy-next launchers (adopts the legacy agy)
  agx import                      adopt install-antigravity-termux.sh's binary as a release
  agx schedule [--every HOURS]     opt-in next-only cron update (default daily)
  agx unschedule                  remove only the agx cron entry
  agx alias                       print agup alias and PATH setup
  agx help
Launches run under proot with the Termux glibc loader; the binary's own auto-update is disabled.
`;
const MANAGED_MARKER = "# agx managed launcher";
const LEGACY_MARKER = "generated by install-antigravity-termux.sh";
/** Antigravity subcommands that would fight the channel manager if run through a launcher. */
const BLOCKED_SUBCOMMANDS: Record<string, string> = {
  update: "Use agx update to keep the channel pins and Termux launch setup",
  install: "agy install would overwrite the managed launcher with the raw glibc binary; use agx setup",
};

/** Install dispatchers once; future channel changes are a single atomic state update. */
export function setupAgx(ctx: AgxContext, cli: string): void {
  for (const name of ["agx", "agy", "agy-next"]) {
    const file = path.join(ctx.localBin, name);
    if (!existsSync(file)) continue;
    const body = lstatSync(file).isSymbolicLink() ? "" : readFileSync(file, "utf8");
    if (!body.includes(MANAGED_MARKER) && !body.includes(LEGACY_MARKER)) throw new Error(`Refusing to overwrite unmanaged launcher ${file}`);
  }
  for (const [name, channel] of [["agx", ""], ["agy", "stable"], ["agy-next", "next"]]) {
    atomicWrite(path.join(ctx.localBin, name), `#!${ctx.prefix}/bin/bash\n${MANAGED_MARKER}\nexec ${shellQuote(path.join(ctx.prefix, "bin/node"))} ${shellQuote(cli)} ${channel ? `run ${channel} ` : ""}"$@"\n`, 0o755);
  }
}

export function parseAgxArgs(args: string[]): ManagerArgs { return parseManagerArgs(args, { import: [] }); }

/** Replace this process with the channel's binary so the terminal, signals and exit status pass straight through. */
function runChannel(ctx: AgxContext, channel: string, args: string[]): never {
  if (channel !== "stable" && channel !== "next") throw new Error("Expected stable or next");
  const version = readAgxState(ctx)[channel];
  if (!version) throw new Error(`No ${channel} installed; run agx update${channel === "stable" ? " then agx promote" : ""}`);
  const blocked = args[0] !== undefined ? BLOCKED_SUBCOMMANDS[args[0]] : undefined;
  if (blocked) throw new Error(blocked);
  const argv = launchArgv(ctx, agxBinary(ctx, version), args);
  const env = launchEnv();
  if (process.execve) process.execve(argv[0], argv, env);
  const result = spawnSync(argv[0], argv.slice(1), { env, stdio: "inherit" });
  if (result.error) throw result.error;
  process.exit(result.status ?? 1);
}

async function main(): Promise<void> {
  const ctx = agxContext();
  const args = process.argv.slice(2);
  if (args[0] === "run") runChannel(ctx, args[1], args.slice(2));
  const opts = parseAgxArgs(args[0] === "--help" ? ["help"] : args);
  if (opts.command === "help") { console.log(HELP); return; }
  if (opts.command === "alias") { console.log('export PATH="$HOME/.local/bin:$PATH"\nalias agup="agx update"'); return; }
  if (opts.command === "status") {
    const state = readAgxState(ctx);
    let latest: string | null = null, manifestError: string | null = null;
    try { latest = (await fetchAgxManifest(ctx)).version; } catch (e) { manifestError = (e as Error).message; }
    const info = { next: state.next, stable: state.stable, archive: state.archive, latest, manifestError, root: ctx.root, localBin: ctx.localBin };
    console.log(opts.json ? JSON.stringify(info, null, 2) : `stable: ${state.stable ?? "not installed"}\nnext: ${state.next ?? "not installed"}\nlatest: ${latest ?? manifestError}\nlaunchers: ${ctx.localBin}`);
    return;
  }
  if (opts.command === "list") { console.log(JSON.stringify({ ...readAgxState(ctx), installed: installedAgx(ctx) }, null, 2)); return; }
  await withDirLock(ctx.root, "agx", async () => {
    const cli = path.resolve(process.argv[1]);
    if (opts.command === "schedule" || opts.command === "unschedule") {
      scheduleAgx(ctx, cli, opts.command === "schedule" ? opts.hours : undefined);
      console.log(opts.command === "schedule" ? "Scheduled next-only updates. Requires crond running; stable is never promoted automatically." : "Removed agx schedule.");
    }
    if (opts.command === "setup") {
      const imported = importLegacyAgx(ctx);
      setupAgx(ctx, cli);
      console.log(`Installed launchers in ${ctx.localBin}; put that directory first on PATH.${imported ? ` Adopted legacy antigravity ${imported} as a managed release.` : ""}`);
    }
    if (opts.command === "import") {
      const imported = importLegacyAgx(ctx);
      console.log(imported ? `Adopted legacy antigravity ${imported}.` : `No legacy binary at ${ctx.legacyBinary}.`);
    }
    if (opts.command === "update") console.log(JSON.stringify(await updateAgx(ctx, opts.value), null, 2));
    if (opts.command === "promote" || opts.command === "rollback") console.log(JSON.stringify(switchAgx(ctx, opts.command === "rollback", opts.value), null, 2));
    if (opts.command === "prune") console.log(JSON.stringify({ applied: opts.yes, removed: pruneAgx(ctx, opts.keep, opts.yes) }, null, 2));
  });
}
if (require.main === module) main().catch(error => { console.error(`agx: ${(error as Error).message}`); process.exitCode = 1; });
