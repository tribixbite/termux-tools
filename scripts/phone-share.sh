#!/data/data/com.termux/files/usr/bin/bash
# phone-share — expose this phone's files to a PC as mountable SFTP drives.
#
#   8022  Termux uid: Termux home + shared storage (/storage/emulated/0)
#   8023  Android shell uid via wireless ADB to this same phone (Shizuku/rish
#         fallback): adds Android/data, Android/obb, /data/local/tmp, ...
#
# Windows: install WinFsp + SSHFS-Win, then Explorer > Map network drive with
# the \\sshfs.r\... paths printed by `phone-share status`. SMB is not an option:
# Windows only speaks it on port 445 and unrooted Android cannot bind <1024.
#
# Usage: phone-share setup|start|stop|status|deploy
set -u

readonly STATE_DIR="$HOME/.local/share/phone-share"
readonly BRIDGE="$STATE_DIR/shell-sftp"
readonly CONF="$STATE_DIR/sshd_shell_config"
readonly PID2="$PREFIX/var/run/sshd-phone-share-shell.pid"
readonly REMOTE_DIR=/data/local/tmp/sftpd
# command -> Termux package providing it
readonly DEPS="sshd:openssh ifconfig:net-tools nc:netcat-openbsd nmap:nmap adb:android-tools"

wlan_ip() { ifconfig 2>/dev/null | awk '/^wlan0/{f=1} f&&/inet /{print $2; exit}'; }
self_serial() {
  local ip; ip=$(wlan_ip); [ -n "$ip" ] || return 0
  adb devices 2>/dev/null | awk -v p="$ip:" 'index($1,p)==1 && $2=="device"{print $1; exit}'
}
port_up() { nc -z 127.0.0.1 "$1" 2>/dev/null; }

missing_pkgs() {
  local d out=""
  for d in $DEPS; do command -v "${d%%:*}" >/dev/null 2>&1 || out="$out ${d#*:}"; done
  [ -x "$PREFIX/libexec/sftp-server" ] || out="$out openssh-sftp-server"
  echo "$out"
}

install_cmd() {
  # Respect whichever package manager actually owns this install (pacman or apt).
  if command -v pacman >/dev/null 2>&1 && pacman -Qq bash >/dev/null 2>&1; then
    echo "pacman -S --needed --noconfirm"
  else
    echo "pkg install -y"
  fi
}

# (Re)write the bridge and the second sshd config; cheap, so done on every start
# so that upgrades of this script take effect.
write_state() {
  mkdir -p "$STATE_DIR" "$PREFIX/var/log" "$PREFIX/var/run"
  cat >"$BRIDGE" <<'BRIDGE_EOF'
#!/data/data/com.termux/files/usr/bin/bash
# SFTP subsystem bridge (generated by phone-share): runs OpenSSH sftp-server as
# the Android shell uid via wireless ADB to this phone, or Shizuku/rish.
# stdout is the binary SFTP stream: never print anything else to it.
REMOTE='cd /storage/emulated/0 2>/dev/null; LD_LIBRARY_PATH=/data/local/tmp/sftpd exec /data/local/tmp/sftpd/sftp-server -d /storage/emulated/0'
LOG="$PREFIX/var/log/phone-share-bridge.log"

serial="${PHONE_SHARE_SERIAL:-}"
ip=$(ifconfig 2>/dev/null | awk '/^wlan0/{f=1} f&&/inet /{print $2; exit}')
find_serial() {
  adb devices 2>/dev/null | awk -v p="$ip:" 'index($1,p)==1 && $2=="device"{print $1; exit}'
}
if [ -z "$serial" ] && [ -n "$ip" ]; then
  serial=$(find_serial)
  if [ -z "$serial" ]; then
    # Wireless-debugging port rotates: drop stale entries, scan, reconnect.
    echo "$(date '+%F %T') no adb link, scanning $ip" >>"$LOG"
    adb devices 2>/dev/null | awk -v p="$ip:" 'index($1,p)==1{print $1}' |
      while read -r s; do adb disconnect "$s" >/dev/null 2>&1; done
    for p in $(nmap -sT -p 30000-65535 --open -n "$ip" 2>/dev/null | awk -F/ '/\/tcp +open/{print $1}'); do
      timeout 5 adb connect "$ip:$p" >/dev/null 2>&1
      serial=$(find_serial); [ -n "$serial" ] && break
      adb disconnect "$ip:$p" >/dev/null 2>&1
    done
  fi
fi

if [ -n "$serial" ]; then
  echo "$(date '+%F %T') adb $serial" >>"$LOG"
  exec adb -s "$serial" shell -T "$REMOTE" 2>>"$LOG"
fi
if command -v rish >/dev/null 2>&1; then
  echo "$(date '+%F %T') rish" >>"$LOG"
  exec rish -c "$REMOTE" 2>>"$LOG"
fi
echo "$(date '+%F %T') no adb device for this phone and no rish" >>"$LOG"
exit 1
BRIDGE_EOF
  chmod 755 "$BRIDGE"
  cat >"$CONF" <<CONF_EOF
# Generated by phone-share. Second sshd: normal Termux auth (password/keys),
# but the sftp subsystem runs as the Android shell uid via ADB/Shizuku.
Port 8023
PidFile $PID2
AuthorizedKeysFile .ssh/authorized_keys
PasswordAuthentication yes
Subsystem sftp $BRIDGE
CONF_EOF
}

deploy() {
  local s t
  s=${PHONE_SHARE_SERIAL:-$(self_serial)}
  if [ -z "$s" ]; then
    echo "deploy: no adb connection to this phone ($(wlan_ip)). Enable Wireless debugging, then:"
    echo "  adb pair 127.0.0.1:<pairing-port>   # once, with the 6-digit code"
    echo "  adb connect $(wlan_ip):<port>       # port shown on the Wireless debugging screen"
    return 1
  fi
  t="$PREFIX/tmp/phone-share-sftpd"; mkdir -p "$t"
  cp "$PREFIX/libexec/sftp-server" "$PREFIX/lib/libandroid-support.so" "$t/"
  adb -s "$s" shell "mkdir -p $REMOTE_DIR" &&
    adb -s "$s" push "$t/." "$REMOTE_DIR/" >/dev/null &&
    adb -s "$s" shell "chmod 755 $REMOTE_DIR/sftp-server" &&
    echo "deployed sftp-server to $s:$REMOTE_DIR"
}

setup() {
  local miss; miss=$(missing_pkgs)
  if [ -n "$miss" ]; then
    echo "installing:$miss"
    # shellcheck disable=SC2086
    $(install_cmd) $miss || return 1
  fi
  [ -d "$HOME/storage" ] || termux-setup-storage
  [ -f "$HOME/.termux_authinfo" ] || { echo "set the password Windows will ask for:"; passwd; }
  write_state
  [ -n "$(self_serial)" ] && deploy
  echo "setup done; run: phone-share start"
}

status() {
  local ip u s; ip=$(wlan_ip); u=$(whoami); s=$(self_serial)
  echo "Phone IP: ${ip:-unknown}   user: $u"
  if port_up 8022; then echo "  8022 (Termux view): UP"; else echo "  8022 (Termux view): down"; fi
  if port_up 8023; then echo "  8023 (shell view):  UP"; else echo "  8023 (shell view):  down"; fi
  echo "  adb self-connection: ${s:-none (8023 will rescan, then try rish/Shizuku)}"
  cat <<EOF

Windows (WinFsp + SSHFS-Win), Explorer > Map network drive:
  \\\\sshfs.r\\$u@$ip!8022\\storage\\emulated\\0              shared storage
  \\\\sshfs.r\\$u@$ip!8022\\data\\data\\com.termux\\files\\home   Termux home
  \\\\sshfs.r\\$u@$ip!8023\\storage\\emulated\\0              shared storage incl. Android/data (ADB)
Password = your Termux password (change with: passwd)
EOF
}

start() {
  local miss s; miss=$(missing_pkgs)
  if [ -n "$miss" ]; then
    echo "missing packages:$miss  -> run: phone-share setup  (or: $(install_cmd)$miss)"
    return 1
  fi
  [ -f "$HOME/.termux_authinfo" ] || echo "warning: no Termux password set yet; run: passwd"
  write_state
  s=$(self_serial)
  if [ -n "$s" ] && ! adb -s "$s" shell "test -x $REMOTE_DIR/sftp-server" 2>/dev/null; then
    deploy
  fi
  command -v termux-wake-lock >/dev/null 2>&1 && termux-wake-lock
  port_up 8022 || sshd
  port_up 8023 || sshd -f "$CONF"
  sleep 1
  status
}

stop() {
  if [ -f "$PID2" ] && kill "$(cat "$PID2")" 2>/dev/null; then echo "stopped 8023"; else echo "8023 not running"; fi
  echo "(8022 is the normal Termux sshd and was left running; 'pkill -x sshd' stops both)"
}

case "${1:-status}" in
  setup) setup ;;
  start) start ;;
  stop) stop ;;
  status) status ;;
  deploy) write_state; deploy ;;
  -h | --help | help) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//' ;;
  *) echo "usage: phone-share setup|start|stop|status|deploy" >&2; exit 2 ;;
esac
